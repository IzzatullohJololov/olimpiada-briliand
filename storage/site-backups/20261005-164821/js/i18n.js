const KEY = 'iao-lang';
function detect() {
  try { const s = localStorage.getItem(KEY); if (s && IDX[s] !== undefined) return s; } catch (e) { /* ignore */ }
  const nav = ((navigator.languages && navigator.languages[0]) || navigator.language || 'en').toLowerCase();
  if (nav.startsWith('uz')) return 'uz';
  if (['ru', 'be', 'uk', 'kk', 'ky', 'tg', 'tk'].some((p) => nav.startsWith(p))) return 'ru';
  return 'en';
}

let lang = detect();

export function getLang() { return lang; }
export function setLang(code) {
  if (IDX[code] === undefined) return;
  lang = code;
  try { localStorage.setItem(KEY, code); } catch (e) { /* ignore */ }
  document.documentElement.lang = code;
}
export function t(key, vars) {
  const row = T[key];
  let s = row ? row[IDX[lang]] : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  return s;
}
export function has(key) { return Object.prototype.hasOwnProperty.call(T, key); }
